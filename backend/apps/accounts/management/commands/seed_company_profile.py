class Command(BaseCommand):
    help = "填充云南财税通集团公司简介与企业文化（预览沙箱初始化）"

    def handle(self, *args, **options):
        obj = CompanyProfile.objects.filter(is_deleted=False).first()
        if not obj:
            obj = CompanyProfile.objects.create(intro=INTRO, culture=CULTURE)
            self.stdout.write(self.style.SUCCESS("已创建公司档案并填充简介与企业文化"))
            return
        obj.intro = INTRO
        obj.culture = CULTURE
        obj.save()
        self.stdout.write(self.style.SUCCESS("已更新公司简介与企业文化"))
